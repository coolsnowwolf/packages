pub fn efuse_0x30_transform(raw: u8) -> u8 {
    let mut out = 0u8;
    for (bit, &row) in EFUSE_MATRIX_ROWS.iter().enumerate() {
        if (raw & row).count_ones() & 1 != 0 {
            out |= 1 << bit;
        }
    }
    out ^ EFUSE_XOR_CONST
}
