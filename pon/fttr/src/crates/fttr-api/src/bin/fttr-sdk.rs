use fttr_api::*;
use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs, io,
    path::PathBuf,
};
use ts_rs::TS;

fn render() -> BTreeMap<&'static str, String> {
    let banner = "// Generated by fttr-sdk. Do not edit.\n";
    let mut types = BTreeMap::new();
    struct Types(BTreeMap<String, String>);
    impl ts_rs::TypeVisitor for Types {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if T::output_path().is_none() {
                return;
            }
            let config = ts_rs::Config::default();
            let name = T::name(&config);
            if self.0.contains_key(&name) {
                return;
            }
            self.0
                .insert(name, format!("export {}\n", T::decl(&config)));
            T::visit_dependencies(self);
        }
    }
    fn add<T: TS + 'static>(types: &mut BTreeMap<String, String>) {
        let mut visitor = Types(std::mem::take(types));
        ts_rs::TypeVisitor::visit::<T>(&mut visitor);
        *types = visitor.0;
    }
    let mut generics = Vec::new();
    let mut validators = Vec::new();
    let mut declarations = String::new();
    let mut calls = String::new();
    let mut metadata = String::new();
    let mut imports = BTreeSet::new();
    macro_rules! generate {
        ($( $id:ident, $wire:ident, $sdk:ident, $req:ident, $res:ident, $access:ident, $availability:ident, [$($param:ident),*]; )*) => {$(
            add::<$req>(&mut types);
            add::<$res>(&mut types);
            let method = &$id;
            let sdk = method.sdk_name;
            let result = format!("{}{}Result", sdk[..1].to_uppercase(), &sdk[1..]);
            imports.insert(stringify!($res));
            if !method.params.is_empty() { imports.insert(stringify!($req)); }
            generics.push(format!("{result} extends {}", stringify!($res)));
            validators.push(format!("  {sdk}: {{ parse(value: unknown): {result} }};\n"));
            let tuple = method.params.iter().map(|p| format!("{}[\"{p}\"]", stringify!($req))).collect::<Vec<_>>().join(", ");
            let params = method.params.iter().map(|p| format!("\"{p}\"")).collect::<Vec<_>>().join(", ");
            let params_option = if method.params.is_empty() { String::new() } else { format!("params: [{params}], ") };
            declarations.push_str(&format!("  const raw_{sdk} = rpc.declare<unknown, [{tuple}]>({{ object: \"{OBJECT}\", method: \"{}\", {params_option}reject: true }});\n", method.name));
            let argument = if method.params.is_empty() { String::new() } else { format!("request: {}", stringify!($req)) };
            let values = method.params.iter().map(|p| format!("request.{p}")).collect::<Vec<_>>().join(", ");
            calls.push_str(&format!("    async {sdk}({argument}): Promise<{result}> {{\n      return validators.{sdk}.parse(await raw_{sdk}({values}));\n    }},\n"));
            let feature = match method.availability { Availability::Always => "null", Availability::Npu => "\"npu\"", Availability::Hl202 => "\"device-hl202\"" };
            metadata.push_str(&format!("  {{ method: \"{}\", access: \"{}\", feature: {feature}, params: [{params}] }},\n", method.name, match method.access { Access::Read => "read", Access::Write => "write" }));
        )*};
    }
    fttr_methods!(generate);
    // Async envelopes contain serialized JSON; register their final payloads too.
    add::<CalibrationApplied>(&mut types);
    add::<MibSnapshot>(&mut types);
    add::<HlReportReply>(&mut types);
    add::<HlAccountReply>(&mut types);
    add::<HlExecReply>(&mut types);
    add::<HlQuery>(&mut types);
    add::<FpgaDelta>(&mut types);
    let type_names = imports.into_iter().collect::<Vec<_>>().join(", ");
    let type_source = format!("{banner}{}", types.values().cloned().collect::<String>())
        .lines()
        .map(|line| format!("{}\n", line.trim_end()))
        .collect::<String>();
    let client = format!(
        "{banner}import type {{ {type_names} }} from \"./types\";\n\nexport const fttrMethods = [\n{metadata}] as const;\n\nexport function createFttrClient<{}>(\n  rpc: typeof L.rpc,\n  validators: {{\n{}  }},\n) {{\n{declarations}  return {{\n{calls}  }};\n}}\n",
        generics.join(", "),
        validators.concat()
    );
    BTreeMap::from([("types.ts", type_source), ("luci-client.ts", client)])
}

fn render_acl(template: &str) -> Result<String, Box<dyn std::error::Error>> {
    let mut acl: serde_json::Value = serde_json::from_str(template)?;
    let group = acl
        .get_mut("luci-app-fttr")
        .ok_or("missing FTTR ACL group")?;
    for access in ["read", "write"] {
        let ubus = group[access]["ubus"]
            .as_object_mut()
            .ok_or("missing ubus ACL object")?;
        if ubus.contains_key(OBJECT) {
            return Err(
                "native FTTR grants belong to shared declarations, not the ACL template".into(),
            );
        }
        ubus.insert(OBJECT.into(), serde_json::json!([]));
    }
    macro_rules! grant {
        ($( $id:ident, $wire:ident, $sdk:ident, $req:ident, $res:ident, $access:ident, $availability:ident, [$($param:ident),*]; )*) => {$(
            let access = match $id.access { Access::Read => "read", Access::Write => "write" };
            group[access]["ubus"][OBJECT].as_array_mut().unwrap().push(serde_json::json!($id.name));
        )*};
    }
    fttr_methods!(grant);
    let mut bytes = Vec::new();
    let formatter = serde_json::ser::PrettyFormatter::with_indent(b"\t");
    serde::Serialize::serialize(
        &acl,
        &mut serde_json::Serializer::with_formatter(&mut bytes, formatter),
    )?;
    bytes.push(b'\n');
    Ok(String::from_utf8(bytes)?)
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    let mut check = false;
    let mut output = None;
    let mut args = env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--generate" => {}
            "--out-dir" => {
                output = Some(PathBuf::from(
                    args.next().ok_or("--out-dir requires a path")?,
                ))
            }
            "--help" | "-h" => {
                println!("fttr-sdk [--generate | --check] [--out-dir PATH]");
                return Ok(());
            }
            _ => return Err(format!("unknown argument: {arg}").into()),
        }
    }
    let repository = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(4)
        .ok_or("cannot locate repository root")?
        .to_path_buf();
    let output = output.unwrap_or_else(|| {
        repository
            .parent()
            .unwrap()
            .join("luci-app-fttr/src/api/generated")
    });
    // Require the documented frontend layout before creating any directories.
    let frontend = output
        .parent()
        .and_then(|p| p.parent())
        .and_then(|p| p.parent())
        .ok_or("expected FRONTEND/src/api/generated")?;
    if !frontend.join("package.json").is_file() || !frontend.join("src").is_dir() {
        return Err(format!(
            "frontend not found at {}; use --out-dir FRONTEND/src/api/generated",
            frontend.display()
        )
        .into());
    }
    let mut drift = Vec::new();
    let mut files: BTreeMap<PathBuf, String> = render()
        .into_iter()
        .map(|(name, source)| (output.join(name), source))
        .collect();
    files.insert(
        frontend.join("package/luci-app-fttr/root/usr/share/rpcd/acl.d/luci-app-fttr.json"),
        render_acl(&fs::read_to_string(frontend.join("src/api/acl-base.json"))?)?,
    );
    // Check every output before changing any of them. --check never writes.
    for (name, source) in &files {
        match fs::read_to_string(name) {
            Ok(current) if current == *source => {}
            Ok(_) => drift.push(name.clone()),
            Err(e) if e.kind() == io::ErrorKind::NotFound => drift.push(name.clone()),
            Err(e) => return Err(e.into()),
        }
    }
    if check && !drift.is_empty() {
        return Err(format!(
            "SDK/ACL drift: {}",
            drift
                .iter()
                .map(|p| p.display().to_string())
                .collect::<Vec<_>>()
                .join(", ")
        )
        .into());
    }
    if !check {
        fs::create_dir_all(&output)?;
        for name in &drift {
            let path = name;
            fs::create_dir_all(path.parent().ok_or("invalid output path")?)?;
            let temporary = path.with_extension(format!("{}.tmp", std::process::id()));
            fs::write(&temporary, &files[name])?;
            fs::rename(&temporary, &path)?;
        }
    }
    println!(
        "SDK {}: {}",
        if check { "checked" } else { "generated" },
        output.display()
    );
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("fttr-sdk: {error}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn wire_nulls_and_parameter_mapping() {
        let files = render();
        let types = &files["types.ts"];
        assert!(types.contains("desired_enabled: boolean | null"));
        assert!(types.contains("error: OpticalError | null"));
        let client = &files["luci-client.ts"];
        assert!(client.contains("[OpticalSettings[\"enabled\"], OpticalSettings[\"downstream_tx_enabled\"], OpticalSettings[\"fec_enabled\"]]"));
        assert!(client.contains(
            "raw_opticalSet(request.enabled, request.downstream_tx_enabled, request.fec_enabled)"
        ));
        assert!(client.contains("object: \"fttr\""));
        assert!(types.contains("total_packets: number"));
        assert!(!types.contains("bigint"));
        assert!(types.contains("optical_transceiver: OpticalTransceiverStatus"));
        assert!(types.contains("devices: Array<DeviceSync>"));
        assert!(types.contains("report: MibReport"));
        assert!(!types.contains("Array<unknown>"));
        assert!(client.contains("method: \"npu_status\", access: \"read\", feature: \"npu\""));
        for name in [
            GET_TOPOLOGY.name,
            GET_TOPOLOGY_NODE.name,
            GET_TOPOLOGY_CLIENTS.name,
        ] {
            assert!(client.contains(&format!(
                "method: \"{}\", access: \"read\", feature: null",
                name
            )));
        }
        assert!(types.contains("hl202: TopologyHl202 | null"));
        assert!(types.contains("snapshot_id?: string"));
        assert!(client.contains("raw_getTopologyClients(request.node_id, request.snapshot_id, request.cursor, request.limit)"));
    }

    #[test]
    fn acl_preserves_external_grants_and_rejects_duplicate_native_sources() {
        let template = r#"{"luci-app-fttr":{"read":{"uci":["fttr"],"ubus":{"luci-rpc":["getNetworkDevices"]}},"write":{"uci":["fttr"],"ubus":{}}}}"#;
        let acl: serde_json::Value = serde_json::from_str(&render_acl(template).unwrap()).unwrap();
        let group = &acl["luci-app-fttr"];
        assert_eq!(group["read"]["ubus"]["luci-rpc"][0], "getNetworkDevices");
        assert!(group["read"]["ubus"][OBJECT]
            .as_array()
            .unwrap()
            .contains(&serde_json::json!(MIB_START.name)));
        assert!(group["write"]["ubus"][OBJECT]
            .as_array()
            .unwrap()
            .contains(&serde_json::json!(NPU_SET.name)));
        assert!(render_acl(&acl.to_string()).is_err());
        for name in [
            GET_TOPOLOGY.name,
            GET_TOPOLOGY_NODE.name,
            GET_TOPOLOGY_CLIENTS.name,
        ] {
            assert!(group["read"]["ubus"][OBJECT]
                .as_array()
                .unwrap()
                .contains(&serde_json::json!(name)));
            assert!(!group["write"]["ubus"][OBJECT]
                .as_array()
                .unwrap()
                .contains(&serde_json::json!(name)));
        }
    }
}
